function getStoredLanguage() {
  try {
    const stored = window.localStorage.getItem(LANGUAGE_KEY);
    if (stored === 'en' || stored === 'el') return stored;
  } catch {
    // Storage can be unavailable in private browsing; keep the default language.
  }
  return 'en';
}

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(getStoredLanguage);
  const value = useMemo(() => ({
    language,
    locale: language === 'el' ? 'el-GR' : 'en-GB',
    setLanguage(nextLanguage) {
      if (nextLanguage !== 'en' && nextLanguage !== 'el') return;
      try {
        window.localStorage.setItem(LANGUAGE_KEY, nextLanguage);
      } catch {
        // The current page still uses the selected language without persistence.
      }
      setLanguage(nextLanguage);
    },
  }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  const { language, locale, setLanguage } = context;
  const t = useCallback((key, parameters = {}) => {
    const template = messages[language][key] ?? messages.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name) => (
      parameters[name] === undefined ? match : String(parameters[name])
    ));
  }, [language]);
  return { language, locale, setLanguage, t };
}

export function formatMoney(value, locale) {
  return new Intl.NumberFormat(locale, { style: 'currency', currency: 'EUR' }).format(value);
}
